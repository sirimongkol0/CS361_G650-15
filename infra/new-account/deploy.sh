#!/usr/bin/env bash
# Deploy CS361 V5 into a fresh AWS account, low-cost layout:
# CloudFormation (VPC/EC2/S3/SSM/Secrets) + Cognito + optional Amplify
# + one EC2 instance running the API, PostgreSQL and an optional frontend
# + S3 (files and backups) + EventBridge Scheduler backup.
#
#   infra/new-account/deploy.sh <step> [--apply] [--yes] [--purge]
#
# Steps, in order:
#   check      who am I, which mode (Learner Lab or normal), and service access
#   infra      base stack: VPC, EC2, EIP, S3, SSM parameters, DB secret (plan; --apply to create)
#   cognito    User Pool, app client and role groups as CloudFormation (plan; --apply)
#   amplify    Amplify app + branch as CloudFormation (needs GITHUB_TOKEN_SECRET_ARN)
#   frontend   build and start the EC2/Docker fallback frontend on port 3000
#   backend    upload backend/ and (re)start PostgreSQL + the API over SSM
#   local-auth create/reset local demo accounts (fallback; needs AUTH_BACKEND=local)
#   seed       load fictional demo data into cstu_demo (DELETES its data; needs --yes)
#   schedule   EventBridge Scheduler + SSM backup document + CloudWatch alarm (plan; --apply)
#   backup     pg_dump the database to s3://<bucket>/backups/ (kept 30 days)
#   restore    restore a backup over the current database (needs --yes)
#   status     health check of the API and frontend
#   teardown   delete the V5 stacks; S3 and Cognito are retained (needs --yes)
#              add --purge to also delete the retained S3 bucket and Cognito pool
#
# Without --apply, infra/cognito/amplify/schedule only show what would change;
# frontend and backend are deploy actions. Nothing here prints a password; the database password is generated by
# CloudFormation and read from Secrets Manager on the instance.
#
# Runs from a laptop (set AWS_PROFILE), AWS CloudShell, or an EC2 instance role.
# Learner Lab: set LAB_MODE=true (auto-detected from assumed-role/voclabs) and
# AWS_REGION=us-west-2. Other settings: STACK (default cs361), PROJECT_NAME,
# CONFIG_PREFIX (default /<project>/config), INSTANCE_PROFILE, INSTANCE_TYPE,
# CORS_ORIGINS, GITHUB_TOKEN_SECRET_ARN, AMPLIFY_SERVICE_ROLE_ARN,
# AUTH_BACKEND (cognito default; local is the offline/demo fallback),
# ALERT_EMAIL, BACKUP_SCHEDULE, BACKUP_RETENTION_DAYS.
set -euo pipefail

# Use AWS_PROFILE when the caller sets it; otherwise let the AWS CLI use its
# normal chain (environment credentials, CloudShell, or the EC2 instance profile).
# V5 must work from a self-hosted runner on EC2, where forcing a laptop profile
# such as cstu-new would break the instance role.
export AWS_PAGER=""
STACK="${STACK:-cs361}"
PROJECT_NAME="${PROJECT_NAME:-$STACK}"
LAB_MODE="${LAB_MODE:-auto}"
CONFIG_PREFIX="${CONFIG_PREFIX:-/$PROJECT_NAME/config}"
AUTH_BACKEND="${AUTH_BACKEND:-cognito}"
[[ "$AUTH_BACKEND" == cognito || "$AUTH_BACKEND" == local ]] || { echo "AUTH_BACKEND must be cognito or local" >&2; exit 2; }
POOL_NAME="${POOL_NAME:-cstu-v5-auth}"      # must match infra/new-account/cognito.yaml
CLIENT_NAME="${CLIENT_NAME:-cstu-backend}"
INSTANCE_PROFILE="${INSTANCE_PROFILE:-LabInstanceProfile}"
COGNITO_STACK="${COGNITO_STACK:-$STACK-cognito}"
AMPLIFY_STACK="${AMPLIFY_STACK:-$STACK-amplify}"
BACKUP_STACK="${BACKUP_STACK:-$STACK-backup}"
REPOSITORY="${REPOSITORY:-https://github.com/sirimongkol0/CS361_G650-15}"
BRANCH_NAME="${BRANCH_NAME:-main}"

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
BASE_TEMPLATE="$ROOT/infra/new-account/stack.yaml"
COGNITO_TEMPLATE="$ROOT/infra/new-account/cognito.yaml"
AMPLIFY_TEMPLATE="$ROOT/infra/new-account/amplify.yaml"
BACKUP_TEMPLATE="$ROOT/infra/new-account/backup.yaml"

STEP="${1:-}"; shift || true
APPLY=false; YES=false; PURGE=false; RESTORE_KEY=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --apply) APPLY=true ;;
    --yes) YES=true ;;
    --purge) PURGE=true ;;
    --*) echo "unknown option: $1" >&2; exit 2 ;;
    *) RESTORE_KEY="$1" ;;
  esac
  shift
done

log() { printf '\n== %s\n' "$*"; }
die() { echo "ERROR: $*" >&2; exit 1; }

detect_lab() {
  local arn
  arn=$(aws sts get-caller-identity --query Arn --output text 2>/dev/null || true)
  [[ "$arn" == *"assumed-role/voclabs/"* ]]
}

if [[ "$LAB_MODE" == auto ]]; then
  if detect_lab; then LAB_MODE=true; else LAB_MODE=false; fi
fi
[[ "$LAB_MODE" == true || "$LAB_MODE" == false ]] || die "LAB_MODE must be true, false or auto"
if [[ -z "${AWS_REGION:-}" ]]; then
  if [[ "$LAB_MODE" == true ]]; then AWS_REGION=us-west-2; else AWS_REGION=ap-southeast-2; fi
fi
export AWS_REGION AWS_DEFAULT_REGION="$AWS_REGION"

output_from() {
  local stack=$1 key=$2
  aws cloudformation describe-stacks --stack-name "$stack" \
    --query "Stacks[0].Outputs[?OutputKey=='$key'].OutputValue" --output text 2>/dev/null || true
}
output() { output_from "$STACK" "$1"; }

need() {
  local value=$1 label=$2
  [[ -n "$value" && "$value" != "None" ]] || die "$label not found; run the previous step with --apply"
}

cognito_ids() {
  POOL_ID=$(output_from "$COGNITO_STACK" UserPoolId)
  CLIENT_ID=$(output_from "$COGNITO_STACK" AppClientId)
  if [[ -z "$POOL_ID" || "$POOL_ID" == "None" ]]; then
    POOL_ID=$(aws cognito-idp list-user-pools --max-results 60 \
      --query "UserPools[?Name=='$POOL_NAME'].Id | [0]" --output text)
  fi
  if [[ -z "$CLIENT_ID" || "$CLIENT_ID" == "None" ]]; then
    if [[ -n "$POOL_ID" && "$POOL_ID" != "None" ]]; then
      CLIENT_ID=$(aws cognito-idp list-user-pool-clients --user-pool-id "$POOL_ID" \
        --query "UserPoolClients[?ClientName=='$CLIENT_NAME'].ClientId | [0]" --output text)
    fi
  fi
  need "$POOL_ID" "Cognito User Pool $POOL_NAME"
  need "$CLIENT_ID" "Cognito app client $CLIENT_NAME"
}

# Run a shell script on the backend instance via SSM and print its output.
run_remote() {
  local instance params command_id status
  instance=$(output InstanceId)
  need "$instance" "InstanceId"
  params=$(python3 -c 'import json,sys; print(json.dumps({"commands": [sys.stdin.read()], "executionTimeout": ["3600"]}))' <<<"$1")
  command_id=$(aws ssm send-command --instance-ids "$instance" --document-name AWS-RunShellScript \
    --comment "$2" --parameters "$params" --query Command.CommandId --output text)
  echo "SSM command $command_id on $instance: $2"
  aws ssm wait command-executed --command-id "$command_id" --instance-id "$instance" || true
  status=$(aws ssm get-command-invocation --command-id "$command_id" --instance-id "$instance" \
    --query Status --output text)
  aws ssm get-command-invocation --command-id "$command_id" --instance-id "$instance" \
    --query '[StandardOutputContent,StandardErrorContent]' --output text | tail -60
  [[ "$status" == "Success" ]] || die "remote step ended with status $status"
}

# Validate and plan/apply a CloudFormation stack. Extra arguments are passed to
# `cloudformation deploy` (normally --parameter-overrides ...).
deploy_stack() {
  local stack=$1 template=$2; shift 2
  [[ -f "$template" ]] || die "template not found: $template"
  aws cloudformation validate-template --template-body "file://$template" >/dev/null
  if ! $APPLY; then
    log "Plan for stack $stack (no changes are made)"
    local out change_set
    if ! out=$(aws cloudformation deploy --stack-name "$stack" --template-file "$template" \
      --capabilities CAPABILITY_IAM --no-execute-changeset "$@" 2>&1); then
      echo "$out" >&2
      die "could not create a change set for $stack"
    fi
    change_set=$(grep -o 'arn:aws:cloudformation:[^ ]*changeSet/[^ ]*' <<<"$out" | head -1 || true)
    if [[ -z "$change_set" ]]; then echo "No changes."; return 0; fi
    aws cloudformation wait change-set-create-complete --change-set-name "$change_set" 2>/dev/null || true
    aws cloudformation describe-change-set --change-set-name "$change_set" \
      --query 'Changes[].ResourceChange.[Action,ResourceType,LogicalResourceId,Replacement]' --output table
    aws cloudformation delete-change-set --change-set-name "$change_set" >/dev/null 2>&1 || true
    echo "Review the changes above, then re-run: $0 $STEP --apply"
    return 0
  fi
  log "Creating/updating stack $stack"
  aws cloudformation deploy --stack-name "$stack" --template-file "$template" \
    --capabilities CAPABILITY_IAM --no-fail-on-empty-changeset "$@"
  aws cloudformation describe-stacks --stack-name "$stack" --query 'Stacks[0].Outputs' --output table
}

# Pack a subdirectory from the working tree (not just HEAD) so local V5 changes
# can be tested before they are committed.
archive_to_s3() {
  local sub=$1 key=$2 bucket=$3 version=$4
  log "Uploading $sub ($version) to s3://$bucket/$key"
  if git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1 && [[ -z "$(git -C "$ROOT" status --porcelain "$sub")" ]]; then
    git -C "$ROOT" archive --format=tar.gz "HEAD" "$sub" | aws s3 cp - "s3://$bucket/$key"
  else
    tar -C "$ROOT" -czf - \
      --exclude=.git --exclude=node_modules --exclude=.next --exclude=.venv \
      --exclude=__pycache__ --exclude='*.db' "$sub" | aws s3 cp - "s3://$bucket/$key"
  fi
}

upload_backup_script() {
  local bucket
  bucket=$(output BucketName)
  need "$bucket" "BucketName"
  aws s3 cp "$ROOT/infra/new-account/backup.sh" "s3://$bucket/deploy/backup.sh" --region "$AWS_REGION" >/dev/null
  run_remote "aws s3 cp s3://$bucket/deploy/backup.sh /opt/cs361/backup.sh --region $AWS_REGION >/dev/null && chmod +x /opt/cs361/backup.sh && echo backup.sh ready" "upload backup.sh"
}

step_check() {
  log "Identity"
  aws sts get-caller-identity --output table
  local mode_label="normal account"
  [[ "$LAB_MODE" == true ]] && mode_label="Learner Lab"
  log "Mode: $mode_label · Region: $AWS_REGION · Stack: $STACK · Config: $CONFIG_PREFIX"
  log "Service access in $AWS_REGION (an explicit SCP deny shows up here)"
  local ok=true
  probe() {
    local out
    if out=$(timeout 30 "$@" 2>&1 >/dev/null); then echo "  OK    ${*:2:2}"
    else ok=false; echo "  FAIL  ${*:2:2}: ${out:-timed out}" | head -c 300; echo; fi
  }
  probe aws cloudformation list-stacks --max-items 1
  probe aws ec2 describe-vpcs --max-items 1
  probe aws s3api list-buckets
  if [[ "$AUTH_BACKEND" == local ]]; then
    echo "  INFO  AUTH_BACKEND=local: Cognito probe skipped"
  else
    probe aws cognito-idp list-user-pools --max-results 1
  fi
  probe aws ssm describe-parameters --max-results 1
  probe aws secretsmanager list-secrets --max-results 1
  probe aws scheduler list-schedules --max-results 1
  probe aws amplify list-apps --max-items 1
  probe aws iam list-roles --max-items 1
  if [[ "$LAB_MODE" == true ]]; then
    echo "  INFO  Learner Lab: IAM create-role/OIDC are intentionally not probed (expected deny)"
  fi
  $ok || die "some services are blocked; fix access before continuing"
}

step_infra() {
  if [[ "$LAB_MODE" == true ]]; then
    log "Learner Lab mode: using instance profile $INSTANCE_PROFILE (no IAM role creation)"
  fi
  local params=(
    ProjectName="$PROJECT_NAME"
    LabMode="$LAB_MODE"
    InstanceProfileName="$INSTANCE_PROFILE"
    AuthBackend="$AUTH_BACKEND"
    ConfigPrefix="$CONFIG_PREFIX"
    CorsOrigins="${CORS_ORIGINS:-http://localhost:3000}"
    BackupRetentionDays="${BACKUP_RETENTION_DAYS:-30}"
  )
  [[ -n "${INSTANCE_TYPE:-}" ]] && params+=(InstanceType="$INSTANCE_TYPE")
  deploy_stack "$STACK" "$BASE_TEMPLATE" --parameter-overrides "${params[@]}"
}

step_cognito() {
  if [[ "$AUTH_BACKEND" == local ]]; then
    log "AUTH_BACKEND=local: skipping the Cognito stack"
    echo "Run with AUTH_BACKEND=cognito to create the User Pool instead."
    return 0
  fi
  local params=(
    ProjectName="$PROJECT_NAME"
    PoolName="$POOL_NAME"
    ClientName="$CLIENT_NAME"
    ConfigPrefix="$CONFIG_PREFIX"
  )
  deploy_stack "$COGNITO_STACK" "$COGNITO_TEMPLATE" --parameter-overrides "${params[@]}"
  $APPLY || return 0

  local pool_id py=python3
  pool_id=$(output_from "$COGNITO_STACK" UserPoolId)
  need "$pool_id" "Cognito UserPoolId"
  [[ -x "$ROOT/backend/.venv/bin/python" ]] && py="$ROOT/backend/.venv/bin/python"
  local args=(--pool-id "$pool_id" --pool-name "$POOL_NAME" --client-name "$CLIENT_NAME" --region "$AWS_REGION" --apply)
  [[ -n "${AWS_PROFILE:-}" ]] && args+=(--profile "$AWS_PROFILE")
  log "Cognito test users (passwords go to ~/.config/cstu/cognito-test-users-<pool-id>.txt)"
  "$py" "$ROOT/infra/provision_cognito.py" "${args[@]}"
}

step_amplify() {
  if [[ -z "${GITHUB_TOKEN_SECRET_ARN:-}" ]]; then
    log "Amplify skipped: GITHUB_TOKEN_SECRET_ARN is not set"
    cat <<EOF
Create a Secrets Manager secret whose JSON has a "token" key:
  aws secretsmanager create-secret --name $PROJECT_NAME/github-token \\
    --secret-string '{"token":"<github-token>"}' --region $AWS_REGION
Then re-run:
  GITHUB_TOKEN_SECRET_ARN=<secret-arn> $0 amplify --apply
Or use the EC2/Docker fallback:
  $0 frontend --apply
EOF
    return 0
  fi
  local api_base
  api_base=$(output ApiBaseUrl); need "$api_base" "ApiBaseUrl"
  local params=(
    ProjectName="$PROJECT_NAME"
    Repository="$REPOSITORY"
    BranchName="$BRANCH_NAME"
    ApiBaseUrl="$api_base"
    OauthTokenSecretArn="$GITHUB_TOKEN_SECRET_ARN"
    AmplifyServiceRoleArn="${AMPLIFY_SERVICE_ROLE_ARN:-}"
    ConfigPrefix="$CONFIG_PREFIX"
  )
  deploy_stack "$AMPLIFY_STACK" "$AMPLIFY_TEMPLATE" --parameter-overrides "${params[@]}" || {
    log "Amplify stack failed; use the EC2/Docker fallback: $0 frontend --apply"
    return 1
  }
  $APPLY || return 0
  local url
  url=$(output_from "$AMPLIFY_STACK" BranchUrl)
  [[ -n "$url" && "$url" != "None" ]] && log "Amplify URL: $url"
  echo "The backend step reads ${CONFIG_PREFIX}/amplify_url from SSM, so no second backend deploy is needed."
}

step_frontend() {
  if ! $APPLY; then
    log "Plan: would upload frontend/ and build/start cs361-frontend on the EC2 instance"
    echo "Re-run with: $0 frontend --apply"
    return 0
  fi
  local bucket instance key version
  bucket=$(output BucketName); need "$bucket" "BucketName"
  instance=$(output InstanceId); need "$instance" "InstanceId"
  version=$(date -u +%Y%m%d%H%M%S)
  key="deploy/frontend-$version.tgz"
  archive_to_s3 frontend "$key" "$bucket" "$version"
  log "Building and starting the EC2/Docker frontend (port 3000)"
  run_remote "$(cat <<EOF
set -euo pipefail
cd /opt/cs361
aws s3 cp "s3://$bucket/$key" frontend.tgz --region $AWS_REGION
rm -rf frontend && tar xzf frontend.tgz
docker build -q -t cs361-frontend:$version \
  --build-arg NEXT_PUBLIC_API_URL=/api/v1 \
  --build-arg NEXT_PUBLIC_API_BROWSER_URL=/api/v1 \
  --build-arg API_PROXY_TARGET=http://cs361-backend:8000 \
  --build-arg NEXT_PUBLIC_DEMO_MODE=false \
  frontend
docker rm -f cs361-frontend 2>/dev/null || true
docker run -d --name cs361-frontend --network cs361 --restart unless-stopped \
  -p 3000:3000 cs361-frontend:$version
for i in \$(seq 1 60); do
  curl -fsS http://localhost:3000/dashboard/public >/dev/null && echo "frontend ready" && exit 0
  sleep 2
done
docker logs --tail 50 cs361-frontend
exit 1
EOF
)" "deploy frontend $version"
  log "Fallback frontend: $(output FrontendUrl)"
}

step_backend() {
  [[ -n "${CORS_ORIGINS:-}" ]] || echo "WARNING: CORS_ORIGINS is not set; the backend will use the Amplify URL, the EC2 frontend URL, or the SSM default."
  if [[ "$AUTH_BACKEND" == local ]]; then
    POOL_ID=""; CLIENT_ID=""
  else
    cognito_ids
  fi
  local bucket key version frontend_url
  bucket=$(output BucketName); need "$bucket" "BucketName"
  version=$(date -u +%Y%m%d%H%M%S)
  key="deploy/backend-$version.tgz"
  archive_to_s3 backend "$key" "$bucket" "$version"
  frontend_url=$(output FrontendUrl)

  log "Starting PostgreSQL and the API (config from SSM + Secrets Manager)"
  run_remote "$(cat <<EOF
set -euo pipefail
cd /opt/cs361
aws s3 cp "s3://$bucket/$key" app.tgz --region $AWS_REGION
rm -rf backend && tar xzf app.tgz
umask 077
CONFIG_PREFIX='$CONFIG_PREFIX'
AUTH_BACKEND_VALUE='$AUTH_BACKEND'
get_param() { aws ssm get-parameter --name "\$CONFIG_PREFIX/\$1" --region $AWS_REGION --query Parameter.Value --output text; }
if [[ "\$AUTH_BACKEND_VALUE" == "local" ]]; then
  LOCAL_AUTH_SECRET_ARN=\$(get_param local_auth_secret_arn)
  LOCAL_AUTH_SECRET=\$(aws secretsmanager get-secret-value --secret-id "\$LOCAL_AUTH_SECRET_ARN" --region $AWS_REGION --query SecretString --output text)
else
  LOCAL_AUTH_SECRET=""
fi
SECRET_ARN=\$(get_param db_secret_arn)
SECRET_JSON=\$(aws secretsmanager get-secret-value --secret-id "\$SECRET_ARN" --region $AWS_REGION --query SecretString --output text)
DB_USER=\$(python3 -c 'import json,sys; print(json.load(sys.stdin)["username"])' <<<"\$SECRET_JSON")
DB_NAME=\$(python3 -c 'import json,sys; print(json.load(sys.stdin)["dbname"])' <<<"\$SECRET_JSON")
DB_PASS=\$(python3 -c 'import json,sys; print(json.load(sys.stdin)["password"])' <<<"\$SECRET_JSON")
OLD_USER=\$(grep '^POSTGRES_USER=' db.env 2>/dev/null | cut -d= -f2- || true)
OLD_DB=\$(grep '^POSTGRES_DB=' db.env 2>/dev/null | cut -d= -f2- || true)
OLD_PASS=\$(grep '^POSTGRES_PASSWORD=' db.env 2>/dev/null | cut -d= -f2- || true)
printf 'POSTGRES_USER=%s\nPOSTGRES_DB=%s\nPOSTGRES_PASSWORD=%s\n' "\$DB_USER" "\$DB_NAME" "\$DB_PASS" > db.env
docker network inspect cs361 >/dev/null 2>&1 || docker network create cs361
if ! docker inspect cs361-db >/dev/null 2>&1; then
  docker run -d --name cs361-db --network cs361 --restart unless-stopped --env-file db.env \
    -v /opt/cs361/pgdata:/var/lib/postgresql/data --memory 300m postgres:16-alpine
fi
docker start cs361-db >/dev/null 2>&1 || true
for i in \$(seq 1 30); do docker exec cs361-db pg_isready -U "\$DB_USER" -d "\$DB_NAME" -q && break; sleep 2; done
# If an older database was initialised with a previous password, rotate it to
# the password now held in Secrets Manager. The value is not written to logs.
if [[ -n "\$OLD_PASS" && ( "\$OLD_USER" != "\$DB_USER" || "\$OLD_PASS" != "\$DB_PASS" ) ]]; then
  docker exec -e PGPASSWORD="\$OLD_PASS" cs361-db psql -U "\$OLD_USER" -d "\$OLD_DB" \
    -c "ALTER USER \"\$DB_USER\" WITH PASSWORD '\$DB_PASS';" >/dev/null 2>&1 || true
fi
AMPLIFY_URL=\$(get_param amplify_url 2>/dev/null || true)
CORS_ORIGINS_VALUE='${CORS_ORIGINS:-}'
[[ -n "\$CORS_ORIGINS_VALUE" ]] || CORS_ORIGINS_VALUE="\$AMPLIFY_URL"
[[ -n "\$CORS_ORIGINS_VALUE" ]] || CORS_ORIGINS_VALUE='$frontend_url'
[[ -n "\$CORS_ORIGINS_VALUE" ]] || CORS_ORIGINS_VALUE=\$(get_param cors_origins)
cat > .env <<ENV
DATABASE_URL=postgresql://\$DB_USER:\$DB_PASS@cs361-db:5432/\$DB_NAME
STORAGE_BACKEND=s3
S3_BUCKET=$bucket
AWS_REGION=$AWS_REGION
AUTH_BACKEND=$AUTH_BACKEND
LOCAL_AUTH_SECRET=\$LOCAL_AUTH_SECRET
COGNITO_REGION=$AWS_REGION
COGNITO_USER_POOL_ID=$POOL_ID
COGNITO_APP_CLIENT_ID=$CLIENT_ID
CORS_ORIGINS=\$CORS_ORIGINS_VALUE
ENV
mkdir -p /opt/cs361/local-auth
docker build -q -t cs361-backend:$version backend
docker rm -f cs361-backend 2>/dev/null || true
docker run -d --name cs361-backend --network cs361 --restart unless-stopped --env-file .env \
  -v /opt/cs361/local-auth:/app/storage \
  -p 8000:8000 cs361-backend:$version
for i in \$(seq 1 30); do
  curl -fsS http://localhost:8000/api/v1/health && exit 0
  sleep 2
done
docker logs --tail 50 cs361-backend
exit 1
EOF
)" "deploy backend $version"
  step_status
  if [[ "$AUTH_BACKEND" == local ]]; then
    step_local_auth
  fi
}

# Fallback for environments where Cognito cannot be created. Cognito remains
# the default; this step is a no-op unless AUTH_BACKEND=local.
step_local_auth() {
  [[ "$AUTH_BACKEND" == local ]] || die "local-auth requires AUTH_BACKEND=local"
  run_remote "docker exec cs361-backend python local_auth_setup.py --password-file /app/storage/local-auth-users.txt" "local auth users"
  echo "Local auth password file: /opt/cs361/local-auth/local-auth-users.txt on the instance (mode 0600)."
  echo "Read it through SSM Session Manager; do not paste it into chat or commit it."
}

step_seed() {
  $YES || die "seed deletes every row in cstu_demo; re-run with --yes to confirm"
  run_remote "$(cat <<'EOF'
set -euo pipefail
cd /opt/cs361
image=$(docker inspect --format '{{.Config.Image}}' cs361-backend)
docker run --rm --network cs361 --env-file .env -e STORAGE_BACKEND=local "$image" python seed_demo.py
EOF
)" "seed demo data"
}

step_backup() {
  upload_backup_script
  run_remote "CONFIG_PREFIX='$CONFIG_PREFIX' bash /opt/cs361/backup.sh backup" "backup database"
}

step_restore() {
  [[ -n "$RESTORE_KEY" ]] || die "usage: $0 restore <s3-key> [--yes]"
  if ! $YES; then
    read -r -p "Restore $RESTORE_KEY over the current database? Type yes: " answer
    [[ "$answer" == "yes" ]] || die "cancelled"
  fi
  upload_backup_script
  run_remote "CONFIG_PREFIX='$CONFIG_PREFIX' bash /opt/cs361/backup.sh restore '$RESTORE_KEY' --yes" "restore database"
}

step_schedule() {
  local instance bucket role account
  instance=$(output InstanceId); need "$instance" "InstanceId"
  bucket=$(output BucketName); need "$bucket" "BucketName"
  role=$(output SchedulerRoleArn)
  if [[ -z "$role" || "$role" == "None" ]]; then
    account=$(aws sts get-caller-identity --query Account --output text)
    role="arn:aws:iam::$account:role/LabRole"
  fi
  if $APPLY; then upload_backup_script; fi
  local params=(
    ProjectName="$PROJECT_NAME"
    InstanceId="$instance"
    BucketName="$bucket"
    SchedulerRoleArn="$role"
    AlertEmail="${ALERT_EMAIL:-}"
    BackupSchedule="${BACKUP_SCHEDULE:-rate(1 day)}"
    RetentionDays="${BACKUP_RETENTION_DAYS:-30}"
    ConfigPrefix="$CONFIG_PREFIX"
  )
  deploy_stack "$BACKUP_STACK" "$BACKUP_TEMPLATE" --parameter-overrides "${params[@]}"
  if $APPLY && [[ -n "${ALERT_EMAIL:-}" ]]; then
    echo "Confirm the SNS email subscription sent to $ALERT_EMAIL before relying on alerts."
  fi
}

step_status() {
  log "Health check"
  local api front
  api=$(output ApiBaseUrl)
  [[ -n "$api" && "$api" != "None" ]] && curl -fsS --max-time 10 "$api/api/v1/health" && echo
  front=$(output_from "$AMPLIFY_STACK" BranchUrl)
  if [[ -z "$front" || "$front" == "None" ]]; then front=$(output FrontendUrl); fi
  if [[ -n "$front" && "$front" != "None" ]]; then
    if curl -fsS --max-time 10 "$front/dashboard/public" >/dev/null; then echo "frontend OK: $front"; else echo "frontend not ready: $front"; fi
  fi
}

step_teardown() {
  $YES || die "teardown deletes the instance and its database; run '$0 backup' first, then re-run with --yes"
  local stack bucket pool_id
  # Capture retained resource names before their stack outputs disappear.
  bucket=$(output BucketName)
  pool_id=$(output_from "$COGNITO_STACK" UserPoolId)
  for stack in "$BACKUP_STACK" "$AMPLIFY_STACK" "$COGNITO_STACK" "$STACK"; do
    if aws cloudformation describe-stacks --stack-name "$stack" >/dev/null 2>&1; then
      log "Deleting stack $stack"
      aws cloudformation delete-stack --stack-name "$stack"
      aws cloudformation wait stack-delete-complete --stack-name "$stack"
    fi
  done
  if $PURGE; then
    if [[ -n "$bucket" && "$bucket" != "None" ]]; then
      log "Purging retained S3 bucket s3://$bucket (all objects and versions)"
      # `s3 rb --force` removes current objects but not noncurrent versions or
      # delete markers. Versioning is enabled on this bucket, so delete every
      # version/marker explicitly before deleting the bucket.
      aws s3 rb "s3://$bucket" --force --region "$AWS_REGION" >/dev/null 2>&1 || true
      local kind tmp count attempts
      for kind in Versions DeleteMarkers; do
        attempts=0
        while [[ "$attempts" -lt 10 ]]; do
          tmp=$(mktemp)
          aws s3api list-object-versions --bucket "$bucket" --region "$AWS_REGION" \
            --query "{Objects: (${kind} || \`[]\`)[].{Key: Key, VersionId: VersionId}}" \
            --output json > "$tmp" 2>/dev/null || true
          count=$(python3 -c 'import json,sys; print(len(json.load(open(sys.argv[1])).get("Objects") or []))' "$tmp" 2>/dev/null || echo 0)
          if [[ "$count" -eq 0 ]]; then rm -f "$tmp"; break; fi
          aws s3api delete-objects --bucket "$bucket" --region "$AWS_REGION" \
            --delete "file://$tmp" >/dev/null 2>&1 || true
          rm -f "$tmp"
          attempts=$((attempts + 1))
        done
      done
      if aws s3api delete-bucket --bucket "$bucket" --region "$AWS_REGION" >/dev/null 2>&1; then
        echo "S3 bucket deleted."
      else
        echo "WARNING: could not delete s3://$bucket; delete its versions and retry." >&2
      fi
    fi
    if [[ -n "$pool_id" && "$pool_id" != "None" ]]; then
      log "Deleting retained Cognito User Pool $pool_id"
      aws cognito-idp delete-user-pool --user-pool-id "$pool_id" --region "$AWS_REGION" || true
    fi
    echo "Purged the retained S3 bucket and Cognito pool."
  else
    echo "Kept by DeletionPolicy: S3 bucket $bucket (with backups/) and Cognito pool $POOL_NAME."
    echo "Use teardown --yes --purge to remove them before a clean recreate."
  fi
  echo "The database password secret and the EC2 database were deleted."
}

case "$STEP" in
  check|infra|cognito|amplify|frontend|backend|seed|schedule|backup|restore|status|teardown) "step_$STEP" ;;
  local-auth) step_local_auth ;;
  *) sed -n '2,35p' "$0"; exit 2 ;;
esac
